function getDayRangeKey(days: number): string | null {
  const range = DAY_RANGES.find((r) => days >= r.min && days <= r.max);
  return range?.key ?? null;
}

function getAgeGroup(age: number): AgeGroup | null {
  if (age >= 0 && age <= 40) return "0-40";
  if (age >= 41 && age <= 60) return "41-60";
  if (age >= 61 && age <= 70) return "61-70";
  if (age >= 71 && age <= 72) return "71-72";
  if (age >= 73 && age <= 74) return "73-74";
  return null;
}

export function getQuoteForApplicant(
  days: number,
  age: number,
  coverage: string
): number | null {
  const dayKey = getDayRangeKey(days);
  const ageGroup = getAgeGroup(age);
  const cov = coverage.toLowerCase().replace(" ", "") as Coverage;

  if (!dayKey || !ageGroup || !["50k", "250k", "500k", "1000k"].includes(cov)) {
    return null;
  }

  const row = INSURANCE_QUOTATION_RATES[dayKey];
  const cost = row?.[ageGroup]?.[cov];
  if (cost == null || cost <= 0) return null;
  return cost;
}

export function calculateTotalQuote(
  fromDate: string,
  toDate: string,
  applicantAges: number[],
  coverage: string
): { total: number; breakdown: { age: number; cost: number }[] } {
  const from = new Date(fromDate);
  const to = new Date(toDate);
  const days = Math.ceil((to.getTime() - from.getTime()) / (1000 * 60 * 60 * 24)) + 1;

  if (days < 1 || applicantAges.length === 0) {
    return { total: 0, breakdown: [] };
  }

  const breakdown: { age: number; cost: number }[] = [];
  let total = 0;

  for (const age of applicantAges) {
    const cost = getQuoteForApplicant(days, age, coverage);
    if (cost === null) {
      return { total: 0, breakdown: [] };
    }
    breakdown.push({ age, cost });
    total += cost;
  }

  return { total, breakdown };
}

/** Deterministic formatter to avoid server/client hydration mismatch */
export function formatCurrency(amount: number): string {
  const n = Math.round(amount);
  return `₹${n.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ",")}`;
}
